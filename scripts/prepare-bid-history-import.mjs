import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import XLSX from 'xlsx-js-style';

const inputPath = path.resolve(process.argv[2] || '입찰일정.xls');
const sourceFile = path.basename(inputPath);
const today = process.argv[3] || new Date().toISOString().slice(0, 10);
const startYear = String(Number(today.slice(0, 4)) - 2);
const periodStart = `${startYear}-01-01`;
const workbook = XLSX.read(readFileSync(inputPath), { type: 'buffer', cellDates: false });
const sheet = workbook.Sheets[workbook.SheetNames[0]];
const sourceRows = XLSX.utils.sheet_to_json(sheet, { defval: '', raw: false });
const validCasePattern = /\d{4}\s*(타경|본경|카경|타채|경매)\s*\d+/;

function clean(value) { return String(value || '').trim(); }
function splitCase(value) {
  const raw = clean(value);
  const marker = raw.match(/\(([^)]+)\)\s*$/);
  const caseNumber = raw.replace(/\s+/g, '').replace(/\([^)]+\)\s*$/, '');
  return { caseNumber, itemNumber: marker ? clean(marker[1]).replace(/\s+/g, '') : '' };
}
function sql(value) { return `'${clean(value).replaceAll("'", "''")}'`; }

const included = [];
const excluded = [];
sourceRows.forEach((row, index) => {
  const sourceRow = index + 2;
  const bidDate = clean(row['입찰일']).slice(0, 10);
  const assignee = clean(row['담당자']);
  const court = clean(row['법원']);
  const rawCase = clean(row['사건번호']);
  const bidResult = clean(row['결과']);
  const reasons = [];
  if (!/^\d{4}-\d{2}-\d{2}$/.test(bidDate)) reasons.push('입찰일 형식 오류');
  else if (bidDate < periodStart || bidDate > today) reasons.push(`최근 3개 연도(${periodStart}~${today}) 외`);
  if (!assignee) reasons.push('담당자 없음');
  if (!court || court === '법원') reasons.push('법원 없음');
  if (!validCasePattern.test(rawCase)) reasons.push('사건번호 형식 불명확');
  if (!bidResult) reasons.push('결과 없음');
  if (reasons.length) {
    excluded.push({ 원본행: sourceRow, 제외사유: reasons.join(', '), ...row });
    return;
  }
  const identity = splitCase(rawCase);
  const id = `historical-bid-${createHash('sha256').update(`${sourceFile}|${sourceRow}`).digest('hex').slice(0, 24)}`;
  included.push({
    id, source_file: sourceFile, source_row: sourceRow, assignee_name: assignee,
    property_type: clean(row['물건종류']) || '미분류', bid_result: bidResult,
    bid_date: bidDate, registered_at: clean(row['등록일']), case_number: identity.caseNumber,
    item_number: identity.itemNumber, court,
  });
});

const sqlLines = [
  '-- Generated by scripts/prepare-bid-history-import.mjs',
  `DELETE FROM historical_bid_statistics WHERE source_file = ${sql(sourceFile)};`,
];
for (let offset = 0; offset < included.length; offset += 150) {
  const chunk = included.slice(offset, offset + 150);
  sqlLines.push(`INSERT INTO historical_bid_statistics
  (id, source_file, source_row, assignee_name, property_type, bid_result, bid_date, registered_at, case_number, item_number, court)
VALUES\n${chunk.map((row) => `(${sql(row.id)}, ${sql(row.source_file)}, ${row.source_row}, ${sql(row.assignee_name)}, ${sql(row.property_type)}, ${sql(row.bid_result)}, ${sql(row.bid_date)}, ${sql(row.registered_at)}, ${sql(row.case_number)}, ${sql(row.item_number)}, ${sql(row.court)})`).join(',\n')};`);
}

mkdirSync(path.resolve('outputs'), { recursive: true });
mkdirSync(path.resolve('.tmp'), { recursive: true });
writeFileSync(path.resolve('.tmp/import-my-statistics-history.sql'), sqlLines.join('\n\n'), 'utf8');
writeFileSync(path.resolve(`d1/import-my-statistics-history-${today.replaceAll('-', '')}.sql`), sqlLines.join('\n\n'), 'utf8');

const output = XLSX.utils.book_new();
const guideRows = [
  ['입찰일정 통계 정제 결과'],
  ['원본 파일', sourceFile],
  ['적용 기간', `${periodStart} ~ ${today}`],
  ['통계 포함', included.length],
  ['제외', excluded.length],
  ['포함 기준', '담당자·법원·정규 사건번호가 있고 최근 3개 연도 내 입찰일인 행'],
  ['가격 정확도', '원본 엑셀에 제안가·실제입찰가·낙찰가 열이 없어 계산하지 않음'],
];
const guide = XLSX.utils.aoa_to_sheet(guideRows);
const includedSheet = XLSX.utils.json_to_sheet(included.map((row) => ({
  원본행: row.source_row, 담당자: row.assignee_name, 물건종류: row.property_type, 결과: row.bid_result,
  입찰일: row.bid_date, 등록일: row.registered_at, 사건번호: row.case_number, 물건번호: row.item_number,
  법원: row.court,
})));
const excludedSheet = XLSX.utils.json_to_sheet(excluded);
for (const ws of [guide, includedSheet, excludedSheet]) {
  const range = XLSX.utils.decode_range(ws['!ref'] || 'A1');
  for (let row = range.s.r; row <= range.e.r; row += 1) {
    for (let col = range.s.c; col <= range.e.c; col += 1) {
      const cell = ws[XLSX.utils.encode_cell({ r: row, c: col })];
      if (!cell) continue;
      cell.s = { ...(cell.s || {}), font: { name: 'Arial', sz: row === 0 ? 11 : 10, bold: row === 0 }, alignment: { vertical: 'center' } };
      if (row === 0) cell.s.fill = { fgColor: { rgb: 'D9EAF7' } };
    }
  }
  ws['!autofilter'] = { ref: ws['!ref'] };
}
guide['!cols'] = [{ wch: 20 }, { wch: 70 }];
includedSheet['!cols'] = [10, 14, 20, 12, 12, 21, 20, 12, 22].map((wch) => ({ wch }));
excludedSheet['!cols'] = [10, 36, 14, 20, 12, 12, 21, 20, 22, 18].map((wch) => ({ wch }));
XLSX.utils.book_append_sheet(output, guide, '안내');
XLSX.utils.book_append_sheet(output, includedSheet, '통계포함');
XLSX.utils.book_append_sheet(output, excludedSheet, '제외검토');
XLSX.writeFile(output, path.resolve('outputs/입찰일정_통계정제.xlsx'));

console.log(JSON.stringify({ input: sourceFile, period_start: periodStart, period_end: today, included: included.length, excluded: excluded.length }, null, 2));
